"""Builds hooks/fonts.ts: trimmed, renamed copies of two SIL OFL fonts, embedded as base64 woff2.

Run with fonttools and brotli installed:
  python fonts/build.py <PirataOne-Regular.ttf> <CinzelDecorative-Bold.ttf>

The sources come from github.com/google/fonts (ofl/pirataone, ofl/cinzeldecorative). Both licences reserve their
font names, so the trimmed copies are renamed; their licences are in fonts/.
"""
import base64, io, sys
from fontTools import subset
from fontTools.ttLib import TTFont

TEXT = ''.join(chr(c) for c in range(0x20, 0x7F))  # printable ASCII: the HUD's titles and level line


def build(src: str, family: str) -> str:
    font = TTFont(src)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga']
    opts.name_IDs = ['*']
    s = subset.Subsetter(opts)
    s.populate(text=TEXT)
    s.subset(font)
    # A trimmed font is a modified version: it may not carry the reserved name.
    for rec in font['name'].names:
        if rec.nameID in (1, 4, 16, 21):
            rec.string = family
        elif rec.nameID in (3, 6):
            rec.string = family.replace(' ', '') + '-Regular'
    out = io.BytesIO()
    font.flavor = 'woff2'
    font.save(out)
    return base64.b64encode(out.getvalue()).decode()


gothic = build(sys.argv[1], 'CastleHud Gothic')
capitals = build(sys.argv[2], 'CastleHud Capitals')
with open('hooks/fonts.ts', 'w') as f:
    f.write('// Generated by fonts/build.py: do not edit. Trimmed, renamed copies of Pirata One (Gothic) and\n')
    f.write('// Cinzel Decorative Bold (Capitals), both under the SIL Open Font License 1.1 (see fonts/).\n\n')
    f.write(f"export const GOTHIC_WOFF2 = '{gothic}'\n")
    f.write(f"export const CAPITALS_WOFF2 = '{capitals}'\n")
print('gothic', len(gothic), 'capitals', len(capitals))
